#!/usr/bin/env bash
# Regenerate main/logo_img.c from the SVG logo (needs ImageMagick + Python Pillow).
# Images are stored as LVGL A8 (alpha only) so the firmware can tint them any colour.
# The logo is rendered on white and "ink" (anything darker than white) becomes opaque,
# so multicolour logos keep their inner white details (e.g. text inside an emblem)
# as see-through cut-outs.
#   logo_big   : whole SVG, 400 px wide (boot splash)
#   logo_small : crop box SMALL_CROP of the 2500 px render, 110 px wide (on the gauge)
set -euo pipefail
cd "$(dirname "$0")/.."
SVG=${1:-logo.svg}
SMALL_CROP=${SMALL_CROP:-}   # "" = whole logo; set e.g. 570x217+258+0 to crop a part of a bigger SVG
TMP=$(mktemp -d)
magick -density 600 -background white "$SVG" -flatten -resize 2500x "$TMP/full.png"
magick "$TMP/full.png" -resize 400x "$TMP/big.png"
if [ -n "$SMALL_CROP" ]; then
    magick "$TMP/full.png" -crop "$SMALL_CROP" +repage -trim +repage -resize 110x "$TMP/small.png"
else
    magick "$TMP/full.png" -resize 110x "$TMP/small.png"
fi
python3 -I - "$TMP/big.png" "$TMP/small.png" > main/logo_img.c <<'PY'
import sys
from PIL import Image
print('/* Generated by tools/svg_to_lvgl.sh - do not edit */\n#include "lvgl.h"\n')
for path, name in zip(sys.argv[1:], ["logo_big", "logo_small"]):
    lum = Image.open(path).convert("L")
    # ink = 255 - luminance, stretched so mid-dark colours (Ford blue) become fully opaque
    a = lum.point(lambda v: min(255, (255 - v) * 255 // 150))
    w, h = a.size
    data = a.tobytes()
    print(f"static const uint8_t {name}_map[] = {{")
    for i in range(0, len(data), 24):
        print("    " + ", ".join(f"0x{b:02X}" for b in data[i:i+24]) + ",")
    print("};\n")
    print(f"""const lv_image_dsc_t {name} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w}}},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
""")
PY
rm -rf "$TMP"
echo "wrote main/logo_img.c"
