#!/usr/bin/env python3
"""Pre-render big speed digits 0-9 as LVGL A8 images (main/digits_img.c).

All digits share one cell size so the readout doesn't jump around.
Usage: python3 -I tools/gen_digits.py [font.ttf] [cap_height_px]
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

font_path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/google-noto/NotoSans-Bold.ttf"
target_h = int(sys.argv[2]) if len(sys.argv) > 2 else 104
root = Path(__file__).resolve().parent.parent

# find the font size whose digit height equals target_h
size = target_h
for _ in range(20):
    f = ImageFont.truetype(font_path, size)
    h = max(f.getbbox(d)[3] - f.getbbox(d)[1] for d in "0123456789")
    if h == target_h:
        break
    size = max(1, round(size * target_h / h))
f = ImageFont.truetype(font_path, size)
boxes = {d: f.getbbox(d) for d in "0123456789"}
top = min(b[1] for b in boxes.values())
bottom = max(b[3] for b in boxes.values())
cell_w = max(b[2] - b[0] for b in boxes.values()) + 4
cell_h = bottom - top

out = ['/* Generated by tools/gen_digits.py - do not edit */', '#include "digits_img.h"', '']
for d in "0123456789":
    b = boxes[d]
    img = Image.new("L", (cell_w, cell_h), 0)
    x = (cell_w - (b[2] - b[0])) // 2 - b[0]
    ImageDraw.Draw(img).text((x, -top), d, font=f, fill=255)
    data = img.tobytes()
    out.append(f"static const uint8_t digit_{d}_map[] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 24]) + ",")
    out.append("};")
out.append("")
out.append("const lv_image_dsc_t speed_digits[10] = {")
for d in "0123456789":
    out.append(f"    {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {cell_w}, .h = {cell_h}, .stride = {cell_w}}},")
    out.append(f"     .data_size = sizeof(digit_{d}_map), .data = digit_{d}_map}},")
out.append("};")
(root / "main/digits_img.c").write_text("\n".join(out) + "\n")
(root / "main/digits_img.h").write_text(f"""#pragma once
#include "lvgl.h"

/* Big speed digits 0-9, alpha-only (A8), {cell_w}x{cell_h} px each. Generated by tools/gen_digits.py */
#define SPEED_DIGIT_W {cell_w}
#define SPEED_DIGIT_H {cell_h}
extern const lv_image_dsc_t speed_digits[10];
""")
print(f"font size {size}px -> cell {cell_w}x{cell_h}")
